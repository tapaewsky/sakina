import Foundation

enum Mood: String, CaseIterable, Identifiable {
    case anxiety, sadness, anger, loss, lonely, gratitude, choice, strength
    var id: String { rawValue }

    var title: String {
        switch self {
        case .anxiety:   "Мне тревожно"
        case .sadness:   "Мне грустно"
        case .anger:     "Я злюсь"
        case .loss:      "Я скорблю"
        case .lonely:    "Мне одиноко"
        case .gratitude: "Хочу благодарить"
        case .choice:    "Не могу решиться"
        case .strength:  "Нет сил"
        }
    }
}

struct Verse: Identifiable, Equatable {
    let id: Int
    let arabic: String
    let text: String
    let source: String
    let moods: [Mood]

    var isAyah: Bool { source.hasPrefix("Сура") }

    /// Ссылка на источник: аят — quran.com, хадис — sunnah.com (по первому сборнику в подписи)
    var link: URL? {
        // На sunnah.com у некоторых хадисов несколько вариантов — ведём сразу на нужный
        let exact = [69: "https://sunnah.com/muslim:2564c"]
        if let url = exact[id] { return URL(string: url) }
        if isAyah {
            // «Сура аш-Шарх, 94:5–6» → quran.com/94/5-6
            guard let m = source.firstMatch(of: /(\d+):(\d+)(?:–(\d+))?/) else { return nil }
            let ayah = m.3.map { "\(m.2)-\($0)" } ?? String(m.2)
            return URL(string: "https://quran.com/\(m.1)/\(ayah)")
        }
        let collections = [("Бухари", "bukhari"), ("Муслим", "muslim"), ("Тирмизи", "tirmidhi"),
                           ("Абу Дауд", "abudawud"), ("Насаи", "nasai")]
        // Берём сборник, который упомянут в подписи раньше остальных
        let found = collections.compactMap { name, slug -> (String.Index, String, Int)? in
            guard let r = source.range(of: name),
                  let m = source[r.upperBound...].firstMatch(of: /\d+/), let n = Int(m.0) else { return nil }
            return (r.lowerBound, slug, n)
        }.min { $0.0 < $1.0 }
        return found.flatMap { URL(string: "https://sunnah.com/\($0.1):\($0.2)") }
    }

    var shareText: String { "\(arabic)\n\n«\(text)»\n— \(source)" }

    static func ofDay(_ date: Date = .now) -> Verse { at(date, slot: 0) }

    /// Текст для части дня: slot 0 — текст дня, остальные — другие тексты того же дня
    static func at(_ date: Date, slot: Int) -> Verse {
        all[(dayNumber(date) + slot * 23) % all.count]
    }

    /// То же, но только среди коротких текстов — для виджетов экрана блокировки
    static func at(_ date: Date, slot: Int, maxLength: Int) -> Verse {
        let pool = all.filter { $0.text.count <= maxLength }
        return pool.isEmpty ? at(date, slot: slot) : pool[(dayNumber(date) * 3 + slot) % pool.count]
    }

    /// Номер календарного дня — одинаковый в любое время суток
    private static func dayNumber(_ date: Date) -> Int {
        let parts = Calendar.current.dateComponents([.year, .month, .day], from: date)
        var utc = Calendar(identifier: .gregorian)
        utc.timeZone = TimeZone(identifier: "UTC")!
        return Int((utc.date(from: parts)?.timeIntervalSinceReferenceDate ?? 0) / 86_400)
    }

    static func random(for mood: Mood?, excluding current: Verse?) -> Verse {
        let pool = all.filter { (mood == nil || $0.moods.contains(mood!)) && $0 != current }
        return pool.randomElement() ?? all[0]
    }
}

